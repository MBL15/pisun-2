package ru.sportplatform.common.enums;

public enum RoleType {
    /** Взрослый пользователь: ищет активности, записывается сам или записывает ребёнка, создаёт свои события. */
    USER,
    /** Детский аккаунт, связанный с родителем. Видит только безопасные проверенные активности. */
    CHILD,
    /** Администратор платформы: допуск организаций, модерация событий и обсуждений, контроль ИИ. */
    ADMIN,
    /** Коллективный аккаунт клуба/сообщества. Публикует события только после допуска. */
    ORGANIZATION
}
