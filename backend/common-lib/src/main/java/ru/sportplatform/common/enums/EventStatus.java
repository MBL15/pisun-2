package ru.sportplatform.common.enums;

public enum EventStatus {
    /** Опубликовано, доступно в выдаче и для записи. */
    PUBLISHED,
    /** ИИ-модератор пометил событие пользователя — ждёт решения администратора, в выдаче не показывается. */
    ON_REVIEW,
    /** Снято с публикации администратором: записаться нельзя даже по прямой ссылке. */
    UNPUBLISHED,
    /** Удалено администратором (мягкое удаление: организатор видит причину). */
    DELETED
}
